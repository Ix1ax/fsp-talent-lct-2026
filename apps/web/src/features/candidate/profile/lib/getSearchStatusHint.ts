import type { SearchStatus } from '@/entities/candidate';

export const getSearchStatusHint = (saved?: SearchStatus) => {
  if (saved === 'open')
    return 'Профиль опубликован: вы активно ищете работу. Изменение статуса вступит в силу после сохранения.';
  if (saved === 'passive')
    return 'Профиль опубликован: вы рассматриваете предложения. Изменение статуса вступит в силу после сохранения.';
  return 'Профиль скрыт. Для публикации нужны оба согласия: выберите «Активно ищу» или «Рассматриваю предложения» и сохраните изменения.';
};
